/**
 * CI-EXT-09. A FHIR 404/410 is an availability warning, not clinical deletion.
 * Tenant-scoped Admin SDK only. No HTTP calls inside a Firestore transaction.
 */
import { createHash } from 'node:crypto';
import type { Firestore } from 'firebase-admin/firestore';
import {
  assertFhirIdentifier, assertFhirSource, fhirImportHeadId, fhirPatientLinkId,
  type ExternalFhirImportType, type FhirImportActor,
  type FhirPatientLink, type FhirSourceRecord,
} from './external-fhir-import';
import {
  siteApprovalDocId, validateFhirSiteApproval, type FhirSiteApproval,
} from '@/lib/interop/fhir-site-approval';

export type FhirAvailabilityState = {
  tenantId: string; patientId: string; sourceId: string;
  resourceType: ExternalFhirImportType; resourceId: string;
  headId: string; sourceReceiptId: string;
  status: 'SUSPECTED_ABSENCE' | 'AVAILABLE_CONFIRMED';
  revision: number; episode: number; caseId: string;
  lastProbeStartedAt: number; lastObservedAt: number; lastEventId: string;
};
export type FhirAvailabilityObservation = {
  db: Firestore; actor: FhirImportActor; sourceId: string;
  resourceType: ExternalFhirImportType; resourceId: string;
  expectedHeadReceiptId: string;
  /** Generated by the server, never accepted from the public request body. */
  probeId: string; probeStartedAt: number;
  expectedBaseUrl?: string; expectedCredentialRevision?: number;
  expectedSiteApprovalId?: string; now?: () => number;
};
export type FhirAvailabilityResult = {
  status: 'SUSPECTED_ABSENCE' | 'AVAILABLE_CONFIRMED' | 'UNCHANGED' | 'STALE_IGNORED';
  eventId: string | null; replay: boolean;
};
type Head = {
  tenantId: string; patientId: string; sourceId: string;
  resourceType: string; resourceId: string; receiptId: string;
};
type Receipt = {
  tenantId: string; patientId: string; sourceId: string;
  resourceType: string; resourceId: string; receiptId: string;
  provenance?: { mappedByVerifiedLink?: string };
};
function sha(v: unknown): string {
  return createHash('sha256').update(JSON.stringify(v)).digest('hex');
}
function validate(args: FhirAvailabilityObservation): void {
  assertFhirIdentifier(args.actor.tenantId, 'FHIR_ABSENCE_TENANT_INVALID');
  assertFhirIdentifier(args.sourceId, 'FHIR_ABSENCE_SOURCE_INVALID');
  assertFhirIdentifier(args.resourceId, 'FHIR_ABSENCE_RESOURCE_INVALID');
  if (!['Patient', 'Encounter', 'Observation'].includes(args.resourceType) ||
      !/^fir_[0-9a-f]{64}$/.test(args.expectedHeadReceiptId) ||
      !/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(args.probeId) ||
      !Number.isSafeInteger(args.probeStartedAt) || args.probeStartedAt < 1) {
    throw new Error('FHIR_ABSENCE_OBSERVATION_INVALID');
  }
}
/** Always use server-captured, authoritative FHIR transport outcomes. */
export async function reconcileFhirReadAvailability(
  args: FhirAvailabilityObservation & { httpStatus: 200 | 404 | 410 },
): Promise<FhirAvailabilityResult> {
  validate(args);
  if (![200, 404, 410].includes(args.httpStatus)) {
    throw new Error('FHIR_ABSENCE_HTTP_STATUS_INVALID');
  }
  const tenantId = args.actor.tenantId;
  const root = args.db.collection('tenants').doc(tenantId);
  const headId = fhirImportHeadId(args.sourceId, args.resourceType, args.resourceId);
  const headRef = root.collection('fhirResourceHeads').doc(headId);
  const stateRef = root.collection('fhirAvailabilityStates').doc(headId);
  const kind = args.httpStatus === 200 ? 'READ_VERIFIED' : 'READ_UNAVAILABLE';
  const eventId = 'fae_' + sha([tenantId, args.sourceId, args.resourceType,
    args.resourceId, args.probeId, kind]);
  const eventRef = root.collection('fhirAvailabilityEvents').doc(eventId);
  const clock = args.now || Date.now;
  return args.db.runTransaction(async tx => {
    const [sourceSnap, headSnap, stateSnap, existingEvent] = await tx.getAll(
      root.collection('fhirSources').doc(args.sourceId), headRef, stateRef, eventRef,
    );
    const source = assertFhirSource(
      sourceSnap.exists ? sourceSnap.data() as FhirSourceRecord : null,
      tenantId, args.sourceId, args.actor, args.resourceType, args.expectedBaseUrl,
    );
    if (source.oauth && (args.expectedCredentialRevision === undefined ||
        !args.expectedSiteApprovalId)) {
      throw new Error('FHIR_ABSENCE_SITE_APPROVAL_REQUIRED');
    }
    if (args.expectedCredentialRevision !== undefined &&
        source.oauth?.credentialRevision !== args.expectedCredentialRevision) {
      throw new Error('FHIR_ABSENCE_CREDENTIAL_CHANGED');
    }
    const head = headSnap.exists ? headSnap.data() as Head : null;
    if (!head || head.tenantId !== tenantId || head.sourceId !== args.sourceId ||
        head.resourceType !== args.resourceType || head.resourceId !== args.resourceId ||
        head.receiptId !== args.expectedHeadReceiptId ||
        !/^[A-Za-z0-9._-]{1,128}$/.test(head.patientId)) {
      throw new Error('FHIR_ABSENCE_HEAD_CHANGED_OR_MISSING');
    }
    const [receiptSnap, patientSnap] = await tx.getAll(
      root.collection('fhirImportedVersions').doc(head.receiptId),
      root.collection('patients').doc(head.patientId),
    );
    const receipt = receiptSnap.exists ? receiptSnap.data() as Receipt : null;
    if (!receipt || receipt.tenantId !== tenantId || receipt.patientId !== head.patientId ||
        receipt.receiptId !== head.receiptId || receipt.sourceId !== args.sourceId ||
        receipt.resourceType !== args.resourceType || receipt.resourceId !== args.resourceId ||
        !patientSnap.exists || patientSnap.get('mergedIntoPatientId') ||
        (patientSnap.get('tenantId') && patientSnap.get('tenantId') !== tenantId)) {
      throw new Error('FHIR_ABSENCE_LINEAGE_INVALID');
    }
    const linkId = receipt.provenance?.mappedByVerifiedLink || '';
    if (!/^fpl_[0-9a-f]{64}$/.test(linkId)) throw new Error('FHIR_ABSENCE_LINK_MISSING');
    const linkSnap = await tx.get(root.collection('fhirPatientLinks').doc(linkId));
    const link = linkSnap.exists ? linkSnap.data() as FhirPatientLink : null;
    if (!link || link.tenantId !== tenantId || link.sourceId !== args.sourceId ||
        link.patientId !== head.patientId || link.facilityId !== source.facilityId ||
        link.matchStatus !== 'VERIFIED' || link.consentStatus !== 'GRANTED' ||
        fhirPatientLinkId(args.sourceId, link.externalPatientId) !== linkId) {
      throw new Error('FHIR_ABSENCE_LINK_OR_CONSENT_INVALID');
    }
    if (args.expectedCredentialRevision !== undefined) {
      if (source.siteApprovalId !== args.expectedSiteApprovalId) {
        throw new Error('FHIR_ABSENCE_SITE_APPROVAL_CHANGED');
      }
      const approvalSnap = await tx.get(
        root.collection('fhirSiteApprovals').doc(siteApprovalDocId(source)),
      );
      validateFhirSiteApproval(source,
        approvalSnap.exists ? approvalSnap.data() as FhirSiteApproval : null,
        args.resourceType, clock());
    }
    const state = stateSnap.exists ? stateSnap.data() as FhirAvailabilityState : null;
    if (state && (state.tenantId !== tenantId ||
        state.patientId !== head.patientId || state.sourceId !== args.sourceId ||
        state.headId !== headId || state.resourceId !== args.resourceId ||
        state.resourceType !== args.resourceType ||
        !Number.isSafeInteger(state.revision) || state.revision < 1 ||
        !Number.isSafeInteger(state.episode) || state.episode < 1 ||
        !Number.isSafeInteger(state.lastProbeStartedAt))) {
      throw new Error('FHIR_ABSENCE_STATE_INVALID');
    }
    if (existingEvent.exists) {
      const previous = existingEvent.data()!;
      if (previous.probeStartedAt !== args.probeStartedAt ||
          previous.httpStatus !== args.httpStatus ||
          previous.sourceReceiptId !== head.receiptId) {
        throw new Error('FHIR_ABSENCE_REPLAY_CONFLICT');
      }
      return { status: 'UNCHANGED', eventId, replay: true };
    }
    if (args.httpStatus === 200 && (!state ||
        (state.status === 'AVAILABLE_CONFIRMED' &&
         state.sourceReceiptId === head.receiptId))) {
      return { status: 'UNCHANGED', eventId: null, replay: false };
    }
    // An older in-flight read cannot undo a newer observation.
    const stale = !!state && args.probeStartedAt <= state.lastProbeStartedAt;
    if (args.httpStatus === 200 && stale) {
      return { status: 'STALE_IGNORED', eventId: null, replay: false };
    }
    const repeated = args.httpStatus !== 200 && !stale &&
      state?.status === 'SUSPECTED_ABSENCE' && state.sourceReceiptId === head.receiptId;
    const episode = repeated ? state!.episode : (state?.episode || 0) + 1;
    const caseId = args.httpStatus === 200 || stale ? (state?.caseId || '') :
      repeated ? state!.caseId : 'frc_' + sha([headId, episode, 'REMOTE_ABSENCE']);
    const caseRef = caseId ? root.collection('fhirReconciliationCases').doc(caseId) : null;
    const recoveryOfAbsence = args.httpStatus === 200 && state?.status === 'SUSPECTED_ABSENCE';
    const caseSnap = caseRef && (recoveryOfAbsence || repeated)
      ? await tx.get(caseRef) : null;
    if ((recoveryOfAbsence || repeated) &&
        (!caseSnap?.exists || caseSnap.get('status') !== 'OPEN' ||
         caseSnap.get('reason') !== 'REMOTE_RESOURCE_UNAVAILABLE' ||
         caseSnap.get('patientId') !== head.patientId ||
         caseSnap.get('headId') !== headId)) {
      throw new Error('FHIR_ABSENCE_CASE_INVALID');
    }
    const recordedAt = clock();
    const disposition = stale ? 'STALE_IGNORED' :
      args.httpStatus === 200
        ? (recoveryOfAbsence ? 'READ_RECOVERED' : 'NEW_HEAD_VERIFIED')
        : 'PENDING_RECONCILIATION';
    const common = {
      tenantId, patientId: head.patientId,
      sourceId: args.sourceId, resourceType: args.resourceType,
      resourceId: args.resourceId, headId, sourceReceiptId: head.receiptId,
      probeId: args.probeId, probeStartedAt: args.probeStartedAt,
      httpStatus: args.httpStatus, disposition, caseId, recordedAt, eventId,
    };
    tx.create(eventRef, {
      ...common, eventType: kind === 'READ_VERIFIED'
        ? 'EXTERNAL_FHIR_READ_VERIFIED' : 'EXTERNAL_FHIR_READ_UNAVAILABLE',
      immutable: true, clinicalAuthority: false,
    });
    tx.create(root.collection('auditLogs').doc('fau_' + eventId), {
      ...common, actorId: args.actor.actorId, action: kind,
      immutable: true, clinicalAuthority: false,
    });
    tx.create(root.collection('fhirAvailabilityOutbox').doc('fao_' + eventId), {
      ...common, status: 'HELD', destination: 'CI_EXTERNAL_CONTEXT_QUALIFICATION',
      reason: 'Source read state is non-authoritative and cannot imply clinical deletion',
    });
    if (!stale) {
      if (recoveryOfAbsence) {
        tx.update(caseRef!, {
          status: 'RESOLVED', resolution: 'READ_VERIFIED_RECOVERY',
          resolvedAt: recordedAt, resolvedBy: [args.actor.actorId],
          recoveryReceiptId: head.receiptId, recoveryEventId: eventId,
        });
      } else if (!repeated) {
        tx.create(caseRef!, {
          caseId, tenantId, patientId: head.patientId,
          sourceId: args.sourceId, facilityId: source.facilityId,
          resourceType: args.resourceType, resourceId: args.resourceId,
          headId, currentReceiptId: head.receiptId,
          conflictingReceiptId: head.receiptId,
          reason: 'REMOTE_RESOURCE_UNAVAILABLE', status: 'OPEN',
          recordedAt, approvals: [], resolution: null,
          immutableSourceVersion: true,
        });
      }
      tx.set(stateRef, {
        tenantId, patientId: head.patientId, sourceId: args.sourceId,
        resourceType: args.resourceType, resourceId: args.resourceId,
        headId, sourceReceiptId: head.receiptId,
        status: args.httpStatus === 200 ? 'AVAILABLE_CONFIRMED' : 'SUSPECTED_ABSENCE',
        revision: (state?.revision || 0) + 1,
        episode: args.httpStatus === 200 ? state!.episode : episode,
        caseId, lastProbeStartedAt: args.probeStartedAt,
        lastObservedAt: recordedAt, lastEventId: eventId,
      } satisfies FhirAvailabilityState);
    }
    return {
      status: stale ? 'STALE_IGNORED' :
        args.httpStatus === 200 ? 'AVAILABLE_CONFIRMED' : 'SUSPECTED_ABSENCE',
      eventId, replay: false,
    };
  });
}
